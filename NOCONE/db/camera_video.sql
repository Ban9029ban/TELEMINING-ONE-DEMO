CREATE TABLE IF NOT EXISTS camera_video (
  id          INTEGER PRIMARY KEY,
  name        TEXT NOT NULL,
  source      TEXT NOT NULL DEFAULT '',
  source_type TEXT NOT NULL DEFAULT 'video_file',
  camera_ip   TEXT,
  camera_port INTEGER,
  camera_path TEXT,
  camera_user TEXT,
  camera_password TEXT,
  site        TEXT,
  nivel       TEXT,
  map_code    TEXT,
